#!/usr/bin/env python3
"""Generate the LaTeX tables of the corrected MoVoC paper from the MoVoC repository.

Every number and every segmentation in the generated tables is read or computed
from repository files; nothing is typed by hand.

Usage (from anywhere):
    python make_correction_tables.py --repo /path/to/MoVoC --out /path/to/paper/tables

Outputs
    table1_segmentation.tex  real BPE / WordPiece / MoVoC-Tok output on the
                             example words used in the published paper
    table2_final.tex         copied verbatim from the repository
    table3_final.tex         copied verbatim from the repository (FLORES-200)
    table4_final.tex         copied verbatim from the repository
    table5_vocab.tex         vocabulary budget vs realised sizes (configs/movoc_config.json)
    table6_annotations.tex   one real annotation record per language
    table7_opus.tex          OPUS / Mermru results, mean +/- SD recomputed from per_run
    provenance.json          what each table was built from
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import statistics
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

EMPTY = {"-", "\u2013", "\u2014", "", None}
SLOTS = ("prefix", "root", "infix", "suffix", "clitic")

# Words the published paper uses to illustrate segmentation (Table 1, Sec. 7).
EXAMPLES = [
    ("Amharic", "am", "\u12a0\u120d\u1230\u1260\u1229\u121d", "Table 1"),        # አልሰበሩም
    ("Tigrinya", "ti", "\u12a3\u12ed\u1275\u12a8\u12cd\u1295\u1295", "Sec. 7"),   # ኣይትከውንን
    ("Amharic", "am", "\u1218\u121d\u1205\u122d\u1290\u1275", "Sec. 7"),          # መምህርነት
]

# Published Table 6 example per language; used if it exists in that language's file.
PUBLISHED_T6 = {
    "Amharic": "\u1218\u121d\u1205\u122d\u1290\u1275",   # መምህርነት
    "Tigrinya": "\u121d\u1215\u12f3\u122b\u1275",        # ምሕዳራት
    "Ge'ez": "\u12a5\u121d\u1290\u1275",                 # እምነት
    "Tigre": "\u12a3\u1265\u12ed\u1293",                 # ኣብይና
}
ANNOTATION_FILES = {
    "Amharic": "data/annotations/amharic/postedited_morphemes.json",
    "Tigrinya": "data/annotations/tigrinya/postedited_morphemes.json",
    "Ge'ez": "data/annotations/geez/manual_morphemes.json",
    "Tigre": "data/annotations/tigre/manual_morphemes.json",
}
GOLD_FILES = {"am": "evaluation/data/amharic_gold.tsv", "ti": "evaluation/data/tigrinya_gold.tsv"}

T3_JSON = "v2/archive/table3_intrinsic_v1_original/table3_multiseed.json"
FROZEN = {
    "table2_final.tex": "v2/paper/manuscript/tables/table2_final.tex",
    "table3_final.tex": "v2/archive/table3_intrinsic_v1_original/table3_final.tex",
    "table4_final.tex": "v2/paper/manuscript/tables/table4_final.tex",
}


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:16]


ETH_RUN = re.compile(r"-?[\u1200-\u139F\u2D80-\u2DDF]+(?:-[\u1200-\u139F\u2D80-\u2DDF]+)*-?")


def eth(s: str) -> str:
    """Wrap Ethiopic runs in \\eth{} (defined in main.tex) so XeLaTeX uses the Ethiopic font."""
    return ETH_RUN.sub(lambda m: "\\eth{" + m.group(0) + "}", s)


def tex_escape(s: str) -> str:
    return s.replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


def load_tokenizers(repo: Path):
    sys.path.insert(0, str(repo / "scripts"))
    import evaluate_intrinsic as E  # noqa: E402

    t = repo / "tokenizers"
    return {
        "bpe": E.HFTokenizer(t / "bpe_32k", "BPE"),
        "wp": E.HFTokenizer(t / "wordpiece_32k", "WordPiece"),
        "am": E.MoVoCTokenizer(t / "amharic_movoc_tok_32k", "MoVoC-Tok (am)"),
        "ti": E.MoVoCTokenizer(t / "tigrinya_movoc_tok_32k", "MoVoC-Tok (ti)"),
    }


def gold_lookup(repo: Path, lang: str, word: str) -> str | None:
    f = GOLD_FILES.get(lang)
    if not f:
        return None
    for line in (repo / f).read_text(encoding="utf8").splitlines():
        parts = line.split("\t")
        if parts and parts[0] == word:
            return parts[1].replace("+", "-")
    return None


def table1(repo: Path, tok) -> tuple[str, list]:
    rows, prov = [], []
    for lang_name, lang, word, src in EXAMPLES:
        movoc = tok[lang]
        seg = {
            "BPE": "-".join(tok["bpe"].segment(word)),
            "WordPiece": "-".join(tok["wp"].segment(word)),
            "MoVoC-Tok": "-".join(movoc.segment(word)),
        }
        gold = gold_lookup(repo, lang, word) or "--"
        rows.append(f"{word} & {lang_name} & {gold} & {seg['BPE']} & {seg['WordPiece']} & {seg['MoVoC-Tok']} \\\\")
        prov.append({"word": word, "language": lang_name, "published_in": src, "gold": gold, **seg})
    body = "\n".join(rows)
    tex = (
        "% Generated by make_correction_tables.py -- do not edit by hand.\n"
        "\\begin{tabular}{llllll}\n\\toprule\n"
        "Word & Lang. & Gold & BPE & WordPiece & MoVoC-Tok \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n"
    )
    return tex, prov


def table5(repo: Path) -> tuple[str, dict]:
    c = json.loads((repo / "configs/movoc_config.json").read_text())
    rows = [
        ("Amharic morphemes", c["s_morpheme"], c["v_morpheme_amharic"]),
        ("Amharic BPE", c["s_bpe"], c["v_bpe_amharic"]),
        ("Tigrinya morphemes", c["s_morpheme"], c["v_morpheme_tigrinya"]),
        ("Tigrinya BPE", c["s_bpe"], c["v_bpe_tigrinya"]),
        ("Bilingual MoVoC (union)", c["s"], c["v_movoc"]),
    ]
    body = "\n".join(f"{n} & {b:,} & {v:,} \\\\" for n, b, v in rows)
    tex = (
        "% Generated by make_correction_tables.py from configs/movoc_config.json.\n"
        "\\begin{tabular}{lrr}\n\\toprule\n"
        "Vocabulary & Budget & Realised size \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n"
    )
    return tex, {k: c[k] for k in ("s", "r", "s_lang", "s_bpe", "s_morpheme", "v_morpheme_amharic",
                                   "v_morpheme_tigrinya", "v_bpe_amharic", "v_bpe_tigrinya", "v_movoc")}


def norm(rec: dict) -> dict:
    return {k.lower(): v for k, v in rec.items()}


def slot(v) -> str:
    if v is None or str(v).strip() in EMPTY:
        return "--"
    return str(v).strip()


def table6(repo: Path) -> tuple[str, list]:
    rows, prov = [], []
    for lang, f in ANNOTATION_FILES.items():
        recs = [norm(r) for r in json.loads((repo / f).read_text(encoding="utf8"))]
        pick = next((r for r in recs if r.get("word") == PUBLISHED_T6[lang]), None)
        reason = "published example present in file"
        if pick is None:
            pick = next(r for r in recs if sum(1 for k in SLOTS if slot(r.get(k)) != "--") >= 2)
            reason = "published example absent; first multi-morpheme record in file"
        cells = [slot(pick.get(k)) for k in SLOTS]
        rows.append(f"{lang} & {pick['word']} & " + " & ".join(cells) + " \\\\")
        prov.append({"language": lang, "file": f, "word": pick["word"], "selection": reason,
                     "published_example": PUBLISHED_T6[lang]})
    tex = (
        "% Generated by make_correction_tables.py -- records copied from data/annotations/.\n"
        "\\begin{tabular}{llccccc}\n\\toprule\n"
        "Language & Word & Prefix & Root & Infix & Suffix & Clitic \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"
    )
    return tex, prov


def table7(repo: Path) -> tuple[str, dict]:
    d = json.loads((repo / T3_JSON).read_text())
    g = defaultdict(list)
    for r in d["per_run"]:
        if r["evaluation_dataset"] == "opus":
            g[(r["direction"], r["tokenizer"])].append(r)
    order_dir = [("en-am", "English $\\rightarrow$ Amharic"), ("en-ti", "English $\\rightarrow$ Tigrinya"),
                 ("en-tig", "English $\\rightarrow$ Tigre$^{\\dagger}$"), ("en-gez", "English $\\rightarrow$ Ge'ez$^{\\dagger}$")]
    order_tok = ["BPE", "WordPiece", "MoVoC-Tok"]
    rows, check = [], {}
    for dkey, dlab in order_dir:
        for t in order_tok:
            runs = sorted(g[(dkey, t)], key=lambda r: r["seed"])
            assert [r["seed"] for r in runs] == [42, 43, 44], (dkey, t)
            assert all(r["status"] == "complete" for r in runs)
            b = [r["bleu"] for r in runs]
            c = [r["chrf"] for r in runs]
            n = runs[0]["num_examples"]
            bm, bs, cm, cs = statistics.mean(b), statistics.stdev(b), statistics.mean(c), statistics.stdev(c)
            rows.append(f"{dlab} & {t} & {n} & {bm:.4f} $\\pm$ {bs:.4f} & {cm:.4f} $\\pm$ {cs:.4f} \\\\")
            check[f"{dkey}/{t}"] = {"n": n, "bleu": [round(bm, 4), round(bs, 4)], "chrf": [round(cm, 4), round(cs, 4)]}
    tex = (
        "% Generated by make_correction_tables.py from per_run records in\n"
        f"% {T3_JSON} (mean and sample SD over seeds 42/43/44).\n"
        "\\begin{tabular}{llrrr}\n\\toprule\n"
        "Direction & Tokenizer & $n$ & BLEU $\\uparrow$ & chrF++ $\\uparrow$ \\\\\n\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n"
    )
    return tex, check


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    repo, out = a.repo.resolve(), a.out.resolve()
    out.mkdir(parents=True, exist_ok=True)

    prov = {"repo": "https://github.com/hailaykidu/MoVoC"}
    try:
        prov["commit"] = subprocess.check_output(["git", "-C", str(repo), "rev-parse", "HEAD"], text=True).strip()
    except Exception:  # noqa: BLE001
        prov["commit"] = "unknown"

    for name, src in FROZEN.items():
        shutil.copyfile(repo / src, out / name)
        prov[name] = {"copied_from": src, "sha256_16": sha(repo / src)}

    tok = load_tokenizers(repo)
    for name, fn in (("table1_segmentation.tex", lambda: table1(repo, tok)),
                     ("table5_vocab.tex", lambda: table5(repo)),
                     ("table6_annotations.tex", lambda: table6(repo)),
                     ("table7_opus.tex", lambda: table7(repo))):
        tex, p = fn()
        (out / name).write_text(eth(tex), encoding="utf8")
        prov[name] = p

    (out / "provenance.json").write_text(json.dumps(prov, indent=1, ensure_ascii=False), encoding="utf8")
    print(json.dumps(prov, indent=1, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
